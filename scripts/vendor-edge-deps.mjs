// Bundles the Edge Functions' third-party code into self-contained ESM files under
// supabase/functions/_vendor/. Edge Functions then import nothing from the network at runtime:
// deterministic builds, versions pinned by package-lock.json, smaller supply-chain surface.
// Usage: npm run edge:vendor   (re-run after upgrading libphonenumber-js)
import { readFileSync, writeFileSync } from 'node:fs'
import { rolldown } from 'rolldown'

const version = JSON.parse(readFileSync('node_modules/libphonenumber-js/package.json', 'utf8')).version
const bundle = await rolldown({
  input: 'scripts/edge-vendor-entry.mjs',
  platform: 'neutral',
})
await bundle.write({
  file: 'supabase/functions/_vendor/libphonenumber.js',
  format: 'esm',
  minify: true,
})
await bundle.close()
// Minification drops banners, so prepend provenance afterwards.
const out = 'supabase/functions/_vendor/libphonenumber.js'
writeFileSync(out, `// GENERATED by scripts/vendor-edge-deps.mjs — do not edit.\n// libphonenumber-js@${version} (MIT License), "max" metadata.\n` + readFileSync(out, 'utf8'))
console.log(`Vendored libphonenumber-js@${version}`)
